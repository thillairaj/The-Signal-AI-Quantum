  /* Uniform image sharing. Phone: share the file together with the caption
     text, copy the caption at the same moment, and show the paste notice
     (again after the sheet closes). Desktop: download the image and copy
     the caption, with the same notice. */
  function shareImage(opts) {
    var blob = opts.blob, filename = opts.filename, caption = opts.caption;
    var notify = opts.notify || function () {};
    var file = null;
    try { file = new File([blob], filename, { type: "image/png" }); } catch (e) {}
    if (isMobile() && file && navigator.share) {
      copy(caption).catch(function () {});
      var payload = { files: [file], title: filename, text: caption };
      if (!(navigator.canShare && navigator.canShare(payload))) {
        payload = { files: [file], title: filename };
      }
      notify(NOTICE);
      try {
        var p = navigator.share(payload);
        if (p && p.then) {
          p.then(function () { notify(NOTICE); }, function (e) {
            if (e && e.name !== "AbortError") { download(blob, filename); }
            notify(NOTICE);
          });
        }
      } catch (e) { download(blob, filename); }
    } else {
      download(blob, filename);
      copy(caption).catch(function () {});
      notify(NOTICE);
    }
  }
